import assert from 'node:assert/strict';
import { conversionPayload, downloadEvent, trackConversion } from '../../src/lib/conversionTracking.js';
const origin = 'https://www.smitsircommerce.in';
const anchor = (href, dataset = {}, download = false) => ({ dataset, getAttribute: () => href, hasAttribute: name => name === 'download' && download });
assert.equal(conversionPayload('premium_activation_verified'), null);
assert.equal(conversionPayload('purchase'), null);
const payload = conversionPayload('premium_reference_submitted', { offer: 'lifetime-999', email: 'private@example.test', reference: 'PRIVATE-UTR', value: 999, user_id: 'private', chapter: NaN }, '/premium?reference=secret#private');
assert.deepEqual(payload, { user_id: null, event_name: 'premium_reference_submitted', path: '/premium', metadata: { offer: 'lifetime-999' } });
assert.deepEqual(downloadEvent(anchor('/materials/free.pdf?token=secret'), origin), ['pdf_download_click', { resource: '/materials/free.pdf', access: 'free' }]);
assert.equal(downloadEvent(anchor('https://external.test/notes.pdf'), origin), null);
assert.equal(downloadEvent(anchor('blob:private-session-url'), origin), null);
assert.deepEqual(downloadEvent(anchor('blob:private-session-url', { pdfResource: 'gseb-economics-chapter-2' }), origin), ['pdf_download_click', { resource: 'gseb-economics-chapter-2', access: 'premium' }]);
assert.deepEqual(downloadEvent(anchor('/premium-payment-qr.jpg', {}, true), origin), ['premium_qr_download', { offer: 'lifetime-999' }]);
assert.equal(downloadEvent(anchor('/premium-payment-qr.jpg'), origin), null);
let sent; let google;
globalThis.window = { location: { pathname: '/premium' }, gtag: (...args) => { google = args; } };
globalThis.fetch = async (url, options) => { sent = { url, options }; return { ok: true }; };
assert.equal(await trackConversion('premium_qr_open', { offer: 'lifetime-999', reference: 'secret' }), true);
assert.equal(sent.options.keepalive, true);
assert.equal(JSON.parse(sent.options.body).user_id, null);
assert.equal(sent.options.body.includes('secret'), false);
assert.equal(google[1], 'premium_qr_open');
assert.equal('value' in google[2], false);
assert.equal(await trackConversion('premium_activation_verified'), false);
globalThis.fetch = async () => { throw new Error('offline'); };
assert.equal(await trackConversion('pdf_download_click'), false);
console.log('Conversion privacy, event separation and download tracking checks passed (18 assertions).');
