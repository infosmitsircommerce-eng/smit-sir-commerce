export function scoreDiagnostic(test, answers) {
  let correct = 0;
  const topicMap = new Map();
  test.questions.forEach(([topic, , , answer], index) => {
    const row = topicMap.get(topic) || { topic, correct: 0, total: 0 };
    row.total += 1;
    if (answers[index] === answer) {
      correct += 1;
      row.correct += 1;
    }
    topicMap.set(topic, row);
  });
  const percent = Math.round((correct / test.questions.length) * 100);
  const topics = [...topicMap.values()].sort(
    (a, b) => a.correct / a.total - b.correct / b.total,
  );
  const level =
    percent >= 80
      ? "Board Ready"
      : percent >= 60
        ? "Building Strongly"
        : percent >= 40
          ? "Needs Revision"
          : "Foundation First";
  return {
    correct,
    total: test.questions.length,
    percent,
    level,
    topics,
    weakTopics: topics.slice(0, 3),
  };
}

